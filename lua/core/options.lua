local opt = vim.opt

-------------------------------------------------
-- Line numbers
-------------------------------------------------

opt.number = true
opt.relativenumber = true

-------------------------------------------------
-- Indentation
-------------------------------------------------

opt.tabstop = 2
opt.shiftwidth = 2
opt.expandtab = true
opt.smartindent = true

vim.api.nvim_create_autocmd("FileType", {
  pattern = "*",
  callback = function()
    vim.bo.tabstop = 2
    vim.bo.shiftwidth = 2
    vim.bo.softtabstop = 2
    vim.bo.expandtab = true
  end,
})

-------------------------------------------------
-- Wrapping
-------------------------------------------------

opt.wrap = true

-------------------------------------------------
-- Search
-------------------------------------------------

opt.ignorecase = true
opt.smartcase = true

-------------------------------------------------
-- Cursor line
-------------------------------------------------

opt.cursorline = true
opt.cursorlineopt = "number"

-------------------------------------------------
-- Scroll
-------------------------------------------------

opt.scrolloff = 8

-------------------------------------------------
-- Split behavior
-------------------------------------------------

opt.splitright = true
opt.splitbelow = true

-------------------------------------------------
-- Clipboard
-------------------------------------------------

opt.clipboard = "unnamedplus"

-------------------------------------------------
-- Mouse
-------------------------------------------------

opt.mouse = "a"

-------------------------------------------------
-- True color
-------------------------------------------------

opt.termguicolors = true

-------------------------------------------------
-- Sign column
-------------------------------------------------

opt.signcolumn = "yes:1"

-------------------------------------------------
-- Update time
-------------------------------------------------

opt.updatetime = 250

-------------------------------------------------
-- Timeout
-------------------------------------------------

vim.o.timeout = true
vim.o.timeoutlen = 500

-------------------------------------------------
-- NETRW
-------------------------------------------------

vim.g.loaded_netrw = 1
vim.g.loaded_netrwPlugin = 1

vim.opt.fillchars:append({
  vert = "│",
})
