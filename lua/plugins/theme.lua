local colors = require("core.colors")

return {

  -------------------------------------------------
  -- KANAGAWA
  -------------------------------------------------
  {
    "rebelot/kanagawa.nvim",
    priority = 1000,

    config = function()

      -------------------------------------------------
      -- Kanagawa setup
      -------------------------------------------------

      require("kanagawa").setup({

        -------------------------------------------------
        -- Theme style
        -------------------------------------------------

        theme = "wave",

        -------------------------------------------------
        -- Transparency
        -------------------------------------------------

        transparent = true,

        -------------------------------------------------
        -- Cleaner gutters
        -------------------------------------------------

        colors = {
          theme = {
            all = {
              ui = {
                bg_gutter = "none",
              },
            },
          },
        },

        -------------------------------------------------
        -- Custom highlights
        -------------------------------------------------

        overrides = function()

          return {

            -------------------------------------------------
            -- Cursor line
            -------------------------------------------------

            CursorLine = {
              bg = "NONE",
            },

            -------------------------------------------------
            -- Line numbers
            -------------------------------------------------

            LineNr = {
              fg = colors.muted,
            },

            CursorLineNr = {
              fg = colors.primary,
              bold = true,
            },

            -------------------------------------------------
            -- Float borders
            -------------------------------------------------

            FloatBorder = {
              fg = colors.secondary,
              bg = "NONE",
            },

            -------------------------------------------------
            -- Normal floats
            -------------------------------------------------

            NormalFloat = {
              bg = "NONE",
            },

          }

        end,

      })

      -------------------------------------------------
      -- Load theme
      -------------------------------------------------

      vim.cmd.colorscheme("kanagawa")

    end,
  },

}
